"""Export every rule the browser engine needs from the Python modules into one JS module.

Single source of truth: the browser engine (src/nitaq/web/engine/*.js) never hard-codes a
lexicon entry, weight, map or pattern; it imports src/nitaq/web/engine/data.js, which this
script generates from the frozen Python scanner files.  tests/test_nitaq_engine_parity.py
regenerates it and fails if the committed file is stale.

usage: python tools/export_engine_data.py [--check]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nitaq_bench.defenses import d1_keyword as D1          # noqa: E402
from nitaq_bench.defenses import d2_lexicon as L           # noqa: E402
from nitaq_bench.defenses import d2_normalizer as N        # noqa: E402
from nitaq_bench.defenses import d2_scanner as S           # noqa: E402
from nitaq_bench.skillscan import rules as R               # noqa: E402

OUT = ROOT / "src" / "nitaq" / "web" / "engine" / "data.js"


def _table(t: dict) -> dict:
    """str.maketrans table (int -> str|None) as {char: replacement|null}."""
    return {chr(k): v for k, v in t.items()}


def _rx(rx) -> list:
    """A compiled Python pattern as [source, python-flag letters] for pyutil.pyRegex."""
    import re
    flags = "".join(letter for flag, letter in ((re.I, "I"), (re.M, "M"), (re.S, "S")) if rx.flags & flag)
    return [rx.pattern, flags]


def build() -> str:
    data = {
        "normalizer": {
            "ZERO_WIDTH": N.ZERO_WIDTH, "BIDI_CONTROLS": N.BIDI_CONTROLS,
            "DIACRITICS_CLASS": N._DIACRITICS_RE.pattern[1:-1],
            "ARABIC_FOLD": _table(N.ARABIC_FOLD), "HOMOGLYPH_FOLD": _table(N.HOMOGLYPH_FOLD),
            "LEET_FOLD": N.LEET_FOLD, "SENT_END": N._SENT_END, "STRIP_CHARS": N._STRIP_CHARS,
            "DETACHED_ARTICLES": sorted(N._DETACHED_ARTICLES), "ARABIZI_DIGITS": "".join(sorted(N._ARABIZI_DIGITS)),
            "DIGRAPHS": [list(p) for p in N._DIGRAPHS], "AZ_DIGIT": N._AZ_DIGIT, "LOSSY": _table(N._LOSSY),
        },
        "lexicon": {"CONCEPTS": L.CONCEPTS, "WEIGHTS": L.WEIGHTS, "FLAG_THRESHOLD": L.FLAG_THRESHOLD,
                    "WINDOWS": L.WINDOWS, "AR_TO_SKELETON": L.AR_TO_SKELETON},
        "d1": {"VERBS": list(D1._VERBS), "DETERMINERS": list(D1._DETERMINERS), "QUALIFIERS": list(D1._QUALIFIERS),
               "OBJECTS": list(D1._OBJECTS), "PHRASES": list(D1._PHRASES)},
        "scanner": {"PROCLITIC_1": list(S._PROCLITIC_1), "ARTICLES": list(S._ARTICLES), "PREP": list(S._PREP),
                    "SUFFIXES": list(S._SUFFIXES), "AZ_PROCLITIC_SK": list(S._AZ_PROCLITIC_SK)},
        "skillscan": {"SEVERITIES": list(R.SEVERITIES),
                      "SHELL_PATTERNS": [list(p) for p in R.SHELL_PATTERNS],
                      "D2_RULE_SEVERITY": R.D2_RULE_SEVERITY, "BIDI": R.BIDI, "ZERO_WIDTH": R.ZERO_WIDTH,
                      "MAX_BYTES": R.MAX_BYTES,
                      "REGEX": {"EMAIL": _rx(R.EMAIL_RE), "URL": _rx(R.URL_RE),
                                "HTML_COMMENT": _rx(R.HTML_COMMENT_RE), "MD_COMMENT": _rx(R.MD_COMMENT_RE),
                                "HIDDEN_HTML": _rx(R.HIDDEN_HTML_RE), "DATA_URI": _rx(R.DATA_URI_RE),
                                "HEX_BLOB": _rx(R.HEX_BLOB_RE), "B64": _rx(N._B64_RE)}},
    }
    body = json.dumps(data, ensure_ascii=True, indent=1, sort_keys=True)
    return ("// GENERATED by tools/export_engine_data.py from the Python rule files. Do not edit.\n"
            "// Source of truth: src/nitaq_bench/defenses/{d1_keyword,d2_lexicon,d2_normalizer,d2_scanner}.py,\n"
            "// src/nitaq_bench/skillscan/rules.py\n"
            f"const DATA = {body};\nexport default DATA;\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("engine data up to date" if ok else "engine data STALE: run python tools/export_engine_data.py")
        raise SystemExit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
