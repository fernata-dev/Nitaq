"""The Nitaq website (site/): generated pages, real decisions, strict CSP, both languages.

site/index.html, site/en/index.html and site/assets/demo-data.js are generated by
tools/site/build_site.py from site/template.html, tools/site/content.py and Nitaq's own policy
code. A stale page, an unresolved placeholder or a hand-edited decision fails here.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
sys.path.insert(0, str(ROOT / "tools" / "site"))


def test_pages_are_fresh_and_decisions_come_from_the_policy():
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "site" / "build_site.py"), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def _demo() -> dict:
    s = (SITE / "assets" / "demo-data.js").read_text(encoding="utf-8")
    return json.loads(s[s.index("{"):s.rindex("}") + 1])


def test_demo_shows_the_guard_deciding_the_same_for_every_language():
    data = _demo()["data"]["scenarios"]
    assert {sc["id"] for sc in data} >= {"exfil", "ssh", "lookalike", "curl", "taint", "legit"}
    for sc in data:
        decisions = {json.dumps(v["decision"], sort_keys=True) for v in sc["variants"]}
        assert len(decisions) == 1, sc["id"]                    # same call -> same decision, any language
        allowed = sc["variants"][0]["decision"]["allowed"]
        assert allowed == (sc["id"] == "legit"), sc["id"]
        for v in sc["variants"]:                               # mock attacker only
            assert re.findall(r"[\w.-]+@[\w.-]+", v["text"]) in ([], ["attacker@test.local"]), v["text"]


def test_pages_have_strict_csp_no_inline_code_and_resolved_text():
    for page, lang, direction in ((SITE / "index.html", "ar", "rtl"), (SITE / "en" / "index.html", "en", "ltr")):
        html = page.read_text(encoding="utf-8")
        assert f'<html lang="{lang}" dir="{direction}">' in html
        csp = re.search(r'http-equiv="Content-Security-Policy" content="([^"]+)"', html).group(1)
        assert "script-src 'self'" in csp and "connect-src 'self'" in csp and "unsafe" not in csp
        assert "{{" not in html and "<script>" not in html and " style=" not in html and " on" + "click=" not in html
        assert html.count("<h1") == 1
        for m in re.finditer(r'<a [^>]*href="(https?://[^"]+)"[^>]*>', html):
            assert 'rel="noopener noreferrer"' in m.group(0), m.group(0)
        for m in re.finditer(r"<img [^>]*>", html):
            assert re.search(r'alt="[^"]*"', m.group(0)), m.group(0)
        assert "Nitaq reduces the damage" in html or "نِطاق بيقلّل الضرر" in html


def test_both_languages_define_the_same_text():
    import content as C
    assert set(C.T["ar"]) == set(C.T["en"])
    tpl = (SITE / "template.html").read_text(encoding="utf-8")
    used = set(re.findall(r"\{\{(\w+)\}\}", tpl))
    computed = {"lang", "dir", "alt_lang", "root", "brand", "pipx", "pipx_short", "repo", "src_owasp", "src_willison",
                "doc_limits", "doc_install", "doc_integrations", "doc_ai", "doc_readme", "os_tabs", "os_panels", "ledger_static",
                "ag_t1", "ag_t2"}
    assert used - computed <= set(C.T["en"]), sorted(used - computed - set(C.T["en"]))


def test_site_script_has_no_html_sinks_or_other_hosts():
    for f in (SITE / "assets").glob("*.js"):
        src = f.read_text(encoding="utf-8")
        for bad in ("innerHTML", "outerHTML", "insertAdjacentHTML", "eval(", "new Function", "XMLHttpRequest", "WebSocket", "sendBeacon"):
            assert bad not in src, f"{f.name}: {bad}"
        if f.name == "site.js":                    # only the film, from its own <source> (same origin)
            assert re.findall(r"fetch\([^)]*\)", src) == ['fetch(src, {credentials: "same-origin"})'], f.name
            assert 'const src = video.querySelector("source").src;' in src
        elif f.name != "connect.js":               # the connect panel calls only the MCP URL the visitor pastes
            assert not re.search(r"fetch\(", src), f.name
    cx = (SITE / "assets" / "connect.js").read_text(encoding="utf-8")
    assert len(re.findall(r"fetch\(", cx)) == 1 and "fetch(url," in cx and not re.search(r"https?://[\w.-]+\.[a-z]{2,}/", cx)


def test_assembled_folder_has_site_and_app(tmp_path):
    out = tmp_path / "_site"
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "site" / "build_site.py"), "--no-images", "--out", str(out)],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    for rel in ("index.html", "en/index.html", "assets/site.js", "assets/demo-data.js", "assets/img/proxy-taint.png",
                "app/index.html", "app/engine/check.js", "app/fonts/plex-arabic-arabic-700.woff2",
                "assets/film/nitaq-demo.mp4", "assets/film/poster.jpg", "assets/fonts/kufi-900.woff2", "_headers"):
        assert (out / rel).is_file(), rel
    assert not (out / "template.html").exists()


def test_site_script_parses_as_a_module(tmp_path):
    node = shutil.which("node")
    if not node:
        pytest.skip("node not installed")
    for f in (SITE / "assets").glob("*.js"):
        copy = tmp_path / (f.stem + ".mjs")
        copy.write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
        r = subprocess.run([node, "--check", str(copy)], capture_output=True, text=True)
        assert r.returncode == 0, f"{f.name}: {r.stderr[-600:]}"
