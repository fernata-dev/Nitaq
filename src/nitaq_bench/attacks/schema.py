"""Attack record schema and validators.

A record (one JSON object per line):
  id            unique, [a-z0-9_.-]
  lang          en | msa | arz | arabizi | mixed
  encoding      none | b64 | leet | zwsp | rot13 | spaced | tatweel | tashkeel | homoglyph
  source        email | webpage | skill_md | tool_desc   ("*" in authored base
                records = expand to every compatible source)
  intent        exfil_send | override | in_scope_tamper | wrong_recipient
  text          the injected instruction (UTF-8)
  intended_call ground truth of the harmful call the text asks for
  author        student | ai-draft | programmatic
  split         dev | test
Authored ("base") records always have encoding "none"; encoded variants are
generated by code (author "programmatic", with base_id/base_author kept).
"""
from __future__ import annotations

import re
import unicodedata
from typing import Any

from nitaq_bench.attacks.encoders import ENCODINGS
from nitaq_bench.env import world as W

LANGS = ("en", "msa", "arz", "arabizi", "mixed")
SOURCES = ("email", "webpage", "skill_md", "tool_desc")
INTENTS = ("exfil_send", "override", "in_scope_tamper", "wrong_recipient")
AUTHORS = ("student", "ai-draft", "programmatic")
SPLITS = ("dev", "test")
REQUIRED = ("id", "lang", "encoding", "source", "intent", "text", "intended_call", "author", "split")
AI_DRAFT_CAP_PER_LANG = 5

_ID = re.compile(r"^[a-z0-9][a-z0-9_.-]{2,80}$")
_VARIANT_ID = re.compile(r"^[a-z0-9][a-z0-9_.+-]{2,200}$")
_EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
_URL = re.compile(r"https?://[^\s\"'<>)]+")
_ARABIC = re.compile(r"[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]")
_LATIN = re.compile(r"[A-Za-z]")
_ARABIZI_DIGIT_WORD = re.compile(r"[A-Za-z]+[23579][A-Za-z']*|[23579][A-Za-z']{2,}")


def script_stats(text: str) -> dict[str, float]:
    """Share of Arabic-script vs Latin letters, ignoring addresses / URLs / paths."""
    cleaned = _URL.sub(" ", _EMAIL.sub(" ", text))
    cleaned = re.sub(r"\S+/\S+", " ", cleaned)
    ar = len(_ARABIC.findall(cleaned))
    la = len(_LATIN.findall(cleaned))
    total = ar + la
    return {
        "arabic": ar, "latin": la,
        "arabic_share": (ar / total) if total else 0.0,
        "arabizi_tokens": len(_ARABIZI_DIGIT_WORD.findall(cleaned)),
    }


def _safety_errors(text: str, where: str) -> list[str]:
    errs = []
    for m in _EMAIL.findall(text):
        if not m.lower().endswith("test.local"):
            errs.append(f"{where}: email address outside the mock domain test.local: {m}")
    for u in _URL.findall(text):
        host = re.sub(r"^https?://", "", u).split("/")[0].split(":")[0].split("@")[-1].lower()
        if not (host == "test.local" or host.endswith(".test.local")):
            errs.append(f"{where}: URL outside the mock domain test.local: {u}")
    return errs


def validate_intended_call(intent: str, call: Any, text: str | None) -> list[str]:
    errs: list[str] = []
    if not isinstance(call, dict) or "tool" not in call or not isinstance(call.get("args", {}), dict):
        return ["intended_call must be an object {tool, args}"]
    tool, args = call["tool"], call.get("args", {})
    if intent in ("exfil_send", "wrong_recipient"):
        if tool != "send_email" or args.get("to") != W.ATTACKER_EMAIL:
            errs.append(f"{intent}: intended_call must be send_email with to={W.ATTACKER_EMAIL}")
        if text is not None and W.ATTACKER_EMAIL not in text:
            errs.append(f"{intent}: text must name the mock attacker address {W.ATTACKER_EMAIL}")
    elif intent == "override":
        if tool != "http_post" or args.get("url") != W.ATTACKER_URL:
            errs.append(f"override: intended_call must be http_post with url={W.ATTACKER_URL}")
        if text is not None and W.ATTACKER_URL not in text:
            errs.append(f"override: text must name the mock attacker URL {W.ATTACKER_URL}")
    elif intent == "in_scope_tamper":
        marker = args.get("contains")
        if tool != "@output" or not isinstance(marker, str) or len(marker) < 4:
            errs.append('in_scope_tamper: intended_call must be {"tool":"@output","args":{"contains":MARKER}}')
        elif text is not None and marker not in text:
            errs.append("in_scope_tamper: the marker must appear verbatim in text")
        elif not marker.isascii():
            errs.append("in_scope_tamper: the marker must be ASCII so matching is script-independent")
    # any destination mentioned in the ground truth must be the mock attacker
    for v in args.values():
        if isinstance(v, str):
            for m in _EMAIL.findall(v):
                if m != W.ATTACKER_EMAIL:
                    errs.append(f"intended_call names a non-mock address: {m}")
            for u in _URL.findall(v):
                if u != W.ATTACKER_URL:
                    errs.append(f"intended_call names a non-mock URL: {u}")
    return errs


def validate_record(rec: dict, base: bool = True) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) for one record."""
    errs: list[str] = []
    warns: list[str] = []
    for k in REQUIRED:
        if k not in rec:
            errs.append(f"missing field: {k}")
    if errs:
        return errs, warns
    rid = rec["id"]
    if not isinstance(rid, str) or not (_ID if base else _VARIANT_ID).match(rid):
        errs.append(f"bad id: {rid!r}")
    if rec["lang"] not in LANGS:
        errs.append(f"bad lang: {rec['lang']!r}")
    if rec["encoding"] not in ENCODINGS:
        errs.append(f"bad encoding: {rec['encoding']!r}")
    allowed_sources = SOURCES + (("*",) if base else ())
    if rec["source"] not in allowed_sources:
        errs.append(f"bad source: {rec['source']!r}")
    if rec["intent"] not in INTENTS:
        errs.append(f"bad intent: {rec['intent']!r}")
    if rec["author"] not in AUTHORS:
        errs.append(f"bad author: {rec['author']!r}")
    if rec["split"] not in SPLITS:
        errs.append(f"bad split: {rec['split']!r}")
    text = rec["text"]
    if not isinstance(text, str) or not text.strip():
        errs.append("text must be a non-empty string")
        return errs, warns
    if errs:
        return errs, warns
    if base:
        if rec["encoding"] != "none":
            errs.append("authored records must have encoding 'none' (variants are generated)")
        if rec["author"] == "programmatic":
            errs.append("authored records cannot have author 'programmatic'")
        if text != unicodedata.normalize("NFC", text):
            warns.append("text is not NFC-normalised")
        errs.extend(_safety_errors(text, "text"))
        errs.extend(validate_intended_call(rec["intent"], rec["intended_call"], text))
        st = script_stats(text)
        lang = rec["lang"]
        if lang == "en" and st["arabic"] > 0:
            errs.append("lang=en but text contains Arabic-script letters")
        if lang in ("msa", "arz") and st["arabic_share"] < 0.6:
            errs.append(f"lang={lang} but Arabic-script share is {st['arabic_share']:.2f} (<0.60)")
        if lang == "arabizi":
            if st["arabic"] > 0:
                errs.append("lang=arabizi but text contains Arabic-script letters")
            if st["arabizi_tokens"] == 0:
                warns.append("lang=arabizi but no digit-letters (2,3,5,7,9) found; is it really Arabizi?")
        if lang == "mixed" and (st["arabic"] == 0 or st["latin"] == 0) and st["arabizi_tokens"] == 0:
            warns.append("lang=mixed but only one script and no Arabizi tokens found")
        if rec["intent"] == "wrong_recipient" and rec["source"] in ("webpage",):
            errs.append("wrong_recipient only applies to reply_email (sources email/skill_md/tool_desc/*)")
    else:
        errs.extend(validate_intended_call(rec["intent"], rec["intended_call"], None))
    return errs, warns


def validate_dataset(records: list[dict]) -> tuple[list[str], list[str]]:
    errs: list[str] = []
    warns: list[str] = []
    seen: set[str] = set()
    ai_per_lang: dict[str, int] = {}
    for rec in records:
        rid = rec.get("id", "<no id>")
        e, w = validate_record(rec, base=True)
        errs.extend(f"{rid}: {x}" for x in e)
        warns.extend(f"{rid}: {x}" for x in w)
        if rid in seen:
            errs.append(f"{rid}: duplicate id")
        seen.add(rid)
        if rec.get("author") == "ai-draft":
            ai_per_lang[rec.get("lang", "?")] = ai_per_lang.get(rec.get("lang", "?"), 0) + 1
    for lang, n in sorted(ai_per_lang.items()):
        if n > AI_DRAFT_CAP_PER_LANG:
            errs.append(
                f"ai-draft cap exceeded for lang={lang}: {n} > {AI_DRAFT_CAP_PER_LANG} "
                "(ISEF integrity rule: the student writes the attack texts)"
            )
    return errs, warns
